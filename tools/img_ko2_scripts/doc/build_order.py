import json, sys
F = "NotoSerifKR-Regular"; FB = "NotoSerifKR-SemiBold"
def build(name, w, h, ink, rows):
    items, boxes = [], []
    for r in rows:
        t, b, kind = r[0], r[1], r[2]
        it = {"text": t, "font": FB if kind in ("title", "co") else F, "color": ink, "box": b}
        if kind in ("title", "co"): it["align"] = "center"
        elif kind == "c": it["align"] = "center"; it["pt"] = round((b[3] - b[1]) * 1.0)
        else: it["align"] = "left"; it["pt"] = round((b[3] - b[1]) * 1.0)
        if kind == "title": it["tracking"] = 60
        items.append(it)
        boxes.append({"id": t[:8], "box": [b[0] - 4, b[1] - 4, b[2] + 4, b[3] + 4], "cond": "lum<175", "grow": 3, "minblob": 3})
    json.dump({"w": w, "h": h, "items": items}, open('items_%s.json' % name, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    json.dump({"src": "src_%s.png" % name, "boxes": boxes}, open('spec_%s.json' % name, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)

